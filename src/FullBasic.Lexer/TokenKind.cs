namespace FullBasic.Lexer;

/// <summary>
/// All token kinds emitted by the lexer for ISO/IEC 10279 Full BASIC. One value
/// per reserved word so the parser can pattern-match on TokenKind directly.
/// Keyword values use the Kw prefix; symbol punctuation/operators use no prefix.
/// </summary>
public enum TokenKind
{
    // -- Layout & special --
    Unknown,
    EndOfFile,
    Newline,

    // -- Literals --
    NumericLiteral,
    StringLiteral,

    // -- Identifiers --
    Identifier,        // FOO, X1, etc.
    StringIdentifier,  // FOO$, X1$
    LineLabel,         // leading integer at start of a logical line

    // -- Punctuation --
    LParen,
    RParen,
    LBracket,
    RBracket,
    Comma,
    Semicolon,
    Colon,
    Question,
    Hash,              // #channel-number

    // -- Operators (symbol form) --
    Plus,
    Minus,
    Asterisk,
    Slash,
    Caret,
    Ampersand,         // string concatenation
    Equal,
    NotEqual,          // <>
    Less,
    LessEqual,
    Greater,
    GreaterEqual,

    // -- Reserved words --
    // Word-form operators come first, then everything else alphabetically.
    KwAnd,
    KwBand,
    KwBnot,
    KwBor,
    KwBxor,
    KwEqv,
    KwImp,
    KwMod,
    KwNot,
    KwOr,
    KwRemainder,
    KwXor,

    KwAccess,
