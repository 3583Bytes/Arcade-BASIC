    KwElse,
    KwElseif,
    KwEnd,
    KwErase,
    KwError,
    KwException,
    KwExit,
    KwExternal,
    KwFile,
    KwFiles,
    KwFiletype,
    KwFixed,
    KwFn,
    KwFor,
    KwFormat,
    KwFunction,
    KwGo,
    KwGosub,
    KwGoto,
    KwGraph,
    KwHandler,
    KwIdn,
